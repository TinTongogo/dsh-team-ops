/**
 * 看板五档状态的**唯一正文**（宿主侧唯一落点）。
 *
 * 为什么要有这个文件：这五个字原先在四个地方各写一遍 —— 引擎、宿主端点、注入摘要、面板 —— 其中两处的
 * **顺序还不同**（一处是「待办 → 进行中 → 已完成 → 待验收」，另一处是「待办 → 进行中 → 待验收 → 已完成」），
 * 于是同一个会话里，工具回执的状态行与每轮注入的状态行长得不一样，人读到的是两份对不上的读数。
 *
 * 顺序按**流程**排：待办 → 进行中 → 待验收 → 已完成 → 已打回
 * （`待验收` 是"还没收口"的一档，排在 `已完成` 之前；`已打回` 是终点）。
 * 改这里的数组 = 改看板分栏顺序、状态行顺序、以及"枚举外取值"的判据 —— 一处改，四处同。
 *
 * 客户端那半边**引不到这个文件**（它是单文件懒加载模块，没有相对导入面），所以它的那份是**抄写**，
 * 由自检钉住"与这里逐字一致"（`tests/panel-blocks.test.mjs`）。
 */

/** 看板五档，按流程排序。 */
export const BOARD_STATUSES = ['待办', '进行中', '待验收', '已完成', '已打回']

/** 登记后未显式给状态时的落库值。 */
export const BOARD_DEFAULT_STATUS = '待办'

/** 收口那一档：到了它就不再算"未完成"（依赖判定、未完成清单都认它）。 */
export const BOARD_DONE_STATUS = '已完成'

/** 打回那一档（等验收里被打回来的）。 */
export const BOARD_REJECTED_STATUS = '已打回'

/** 状态行五个读数的顺序与名字：**每个名字都要能在界面上逐字找到**（直接用分栏名，不给状态行另起名字）。 */
export const STATUS_LINE_ORDER = BOARD_STATUSES.map((status) => ({ key: status, label: status }))

/**
 * 这个取值是不是看板状态之一。枚举外的取值**如实单列**，不静默并入任何一档。
 * @param value - 待判定的取值。
 * @returns 是五档之一就 true。
 */
export function isBoardStatus(value) {
	return BOARD_STATUSES.indexOf(value) !== -1
}
