/**
 * 团队的**编制上限**（唯一正文）。
 *
 * 为什么单列一个文件：两个半边都要用它 —— 制度层（`team/company-gate.js` 的常量与读数）与
 * 薄的角色感知层（`team/native-layer.js` 的判定）。放在任一边，另一边 import 就会成环。
 *
 * **口径（人的约束 HD-005，修正 HD-004）**：两条规则，一条都不多 ——
 *   ① **同一角色 ≤ `MEMBER_ROLE_MAX` 位**；
 *   ② **在场总人数 ≤ `MEMBER_PRESENT_MAX` 位**。
 * 历史：HD-004 曾经把上限写成"同角色 ≤3 + **在场角色种类 ≤8**"，那条种类限制在 HD-005 里**被删掉** ——
 * 它会在"种类已满 8、但总数远不到 24"时拦住新角色（8 个角色 × 2 位 = 16 位时，第 9 个角色就建不出来）；
 * 人给的理由是"**总数管住就够了，别让种类数卡住新角色**"。
 * **24 = 3 位 × 8 角色**，原先只是上面两条推出来的一个数；HD-005 之后它成了**显式上限**（值不变，名分变了）。
 *
 * 宿主侧**也有**一堵同值的墙：app 自带那份 profile 的 `maxMembers`（默认 8，服务默认 16）在
 * `~/.dsh/profiles/desktop/cordis.patch.yml` 里被覆盖成 **24** —— 两层对齐（现场与依据见
 * `docs/team/verify/编制上限-同角色3-角色种类8.md` 第六节）。改这里的值时，那份覆盖要跟着改。
 *
 * **两层"对齐"的准确说法（复核更正过一次）**：宿主那道硬拒是 `state.members.length >= maxMembers`
 * —— **全部名册行、不按 phase 过滤**。所以第二条（在场总人数）**数全部成员（含 `failed`）**；
 * 第一条（同角色 ≤3）**排除 `failed`**（那是"这一档还能不能干活"的口径）。两条口径不同是**有意**的，
 * 别把其中一条改成另一条的形状（改错就会在"23 位在用 + 1 位 failed"时分叉：插件放行、宿主抛 `TEAM_MEMBER_LIMIT`）。
 */

/** 在场人数的告警线：破线**不拦**，但要在回报里留一行「为什么需要第 N 个」。 */
export const MEMBER_WARN_LINE = 4

/** 同一角色的成员上限（**硬上限**）：在场 + 归档算；到顶拒新建，除非写 `line_reason`。 */
export const MEMBER_ROLE_MAX = 3

/** **在场总人数**上限（**硬上限**，24）：到顶拒新建，除非写 `line_reason`。`failed` 的不占**角色槽位**（但占**在场总人数** —— 它是按名册行数算的）。 */
export const MEMBER_PRESENT_MAX = 24
